#!/bin/bash
# Live test of the source-built nvidia-prolapse vendor image (root; container and session must be stopped).
#   install-vendor-test.sh VENDOR_IMG [angle|nvrm] [MEDIA_CODECS_XML]
# Backs up waydroid.cfg, the LXC config and vendor.img to /var/lib/waydroid/before-vendor-image-test-<ts>/ and
# writes a restore.sh there. Then installs VENDOR_IMG next to the live system.img (official 20260927 GAPPS +
# houdini/Magisk), and generates the container config with PLAIN Waydroid (no nvidia_* key: nothing from a driver
# root is bound; the generator has no vendor-image mode yet). What plain Waydroid lacks is added explicitly:
#   [properties]  ro.hardware.vulkan/egl, disable_gl_preload, the Codec2 ranks (Waydroid itself writes egl=mesa and
#                 no vulkan for an NVIDIA render node), persist.waydroid.refresh_rate=250 (stock SF stalls >= ~333 Hz)
#   config_nodes  /dev/nvidiactl, /dev/nvidia0, /dev/nvidia-modeset (appended after `waydroid upgrade -o`), and a bind
#                 of this GPU's media_codecs_c2.xml (nvc2-xmlgen output; default: the one the current release install
#                 generated) over the image's placeholder /odm/etc/media_codecs_c2.xml, kept in $W/nvidia-vendor-image/
set -euo pipefail
IMG=$1 EGL=${2:-angle} XML=${3:-}
[ "$(id -u)" = 0 ] || { echo "run as root" >&2; exit 1; }
[ -f "$IMG" ] || { echo "no $IMG" >&2; exit 1; }
case "$EGL" in angle|nvrm) ;; *) echo "egl must be angle or nvrm" >&2; exit 1 ;; esac
W=/var/lib/waydroid
if [ "$(systemctl is-active waydroid-container.service)" = active ]; then echo "stop the session and container first" >&2; exit 1; fi
RENDER=
for r in /sys/class/drm/renderD*; do [ "$(cat "$r/device/vendor")" = 0x10de ] && RENDER=/dev/dri/$(basename "$r"); done
[ -n "$RENDER" ] || { echo "no NVIDIA render node" >&2; exit 1; }

if [ ! -f "$W/.vendor-image-test-backup" ]; then
    B=$W/before-vendor-image-test-$(date +%Y%m%d-%H%M%S)
    mkdir -p "$B"
    cp -a "$W/waydroid.cfg" "$W/lxc/waydroid/config_nodes" "$W/waydroid_base.prop" "$B/"
    cp --reflink=auto -a "$W/images/vendor.img" "$B/vendor.img"
    cat > "$B/restore.sh" <<EOF
#!/bin/bash
# restore the state before the vendor-image test (run as root; stops the container)
set -euo pipefail
systemctl stop waydroid-container.service || true
cp -a "$B/waydroid.cfg" $W/waydroid.cfg
cp --reflink=auto -a "$B/vendor.img" $W/images/vendor.img
/usr/bin/waydroid upgrade -o
rm -f $W/.vendor-image-test-backup
echo "restored; start the container and the session as before"
EOF
    chmod +x "$B/restore.sh"
    echo "$B" > "$W/.vendor-image-test-backup"
    echo "backup: $B (restore: $B/restore.sh)"
fi
B=$(cat "$W/.vendor-image-test-backup")

mkdir -p "$W/nvidia-vendor-image"
if [ -n "$XML" ]; then cp "$XML" "$W/nvidia-vendor-image/media_codecs_c2.xml"; fi
[ -f "$W/nvidia-vendor-image/media_codecs_c2.xml" ] || {
    XML=$(readlink -f "$W/nvidia-prolapse")/odm/etc/media_codecs_c2.xml
    [ -f "$XML" ] || { echo "no generated media_codecs_c2.xml (pass one)" >&2; exit 1; }
    cp "$XML" "$W/nvidia-vendor-image/media_codecs_c2.xml"; }
grep -q "Generated by nvc2-xmlgen" "$W/nvidia-vendor-image/media_codecs_c2.xml" || { echo "not an nvc2-xmlgen file" >&2; exit 1; }
chmod 0644 "$W/nvidia-vendor-image/media_codecs_c2.xml"
cp --reflink=auto "$IMG" "$W/images/vendor.img"
python3 -I - "$B/waydroid.cfg" "$W/waydroid.cfg" "$RENDER" "$EGL" <<'PY'
import configparser, sys
src, dst, render, egl = sys.argv[1:5]
c = configparser.ConfigParser(interpolation=None)
c.optionxform = str
c.read(src)
for k in [k for k in c["waydroid"] if k.startswith("nvidia_")]:
    del c["waydroid"][k]
c["waydroid"]["drm_device"] = render
p = c["properties"]
p.update({
    "persist.waydroid.refresh_rate": "250",
    "ro.hardware.vulkan": "nvidia",
    "ro.hardware.egl": egl,
    "ro.zygote.disable_gl_preload": "true",
    "debug.stagefright.ccodec": "4",
    "debug.stagefright.omx_default_rank.sw-audio": "4",
    "debug.stagefright.omx_default_rank.sw-other": "256",
})
with open(dst, "w") as f:
    c.write(f)
PY
/usr/bin/waydroid upgrade -o
systemctl stop waydroid-container.service || true
N=$W/lxc/waydroid/config_nodes
for d in /dev/nvidiactl /dev/nvidia0 /dev/nvidia-modeset; do
    grep -q "^lxc.mount.entry = $d " "$N" || echo "lxc.mount.entry = $d ${d#/} none bind,create=file 0 0" >> "$N"
done
grep -q "media_codecs_c2.xml" "$N" || echo "lxc.mount.entry = $W/nvidia-vendor-image/media_codecs_c2.xml vendor/odm/etc/media_codecs_c2.xml none bind 0 0" >> "$N"
grep -E "nvidia|$RENDER|vendor_extra|nv/guest|odm" "$N" || true
grep -E "ro.hardware|ccodec|refresh_rate|gralloc" "$W/waydroid_base.prop"
echo "installed $(sha256sum "$W/images/vendor.img" | cut -c1-16) with egl=$EGL"
