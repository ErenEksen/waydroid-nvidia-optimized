#!/usr/bin/env python3
"""Generate the EGL entry table of libEGL_nvnative.so from Android's own list.

Input: frameworks/native opengl/libs/EGL/egl_entries.in at the pinned android13-release commit
(the names the Android loader dlsym()s from libEGL_<suffix>.so, Loader.cpp:627-668).
Output: a header with one X(ret, name, (typed params), (args)) row per entry the front exports.

Excluded rows, measured on 615.71.09 (__egl_Main 0.2 + imports.getProcAddress returns NULL for them;
probe: build/p7/probe + this repo's egl/README.md "Measured"): the loader implements
eglGetNativeClientBufferANDROID itself and calls the driver's eglGetProcAddress for anything not
exported, so not exporting them keeps "not provided" visible as NULL instead of a stub.
FRONT rows are implemented by hand in src/front.c.
"""
import re
import sys

EXCLUDED = {
    "eglLockSurfaceKHR", "eglUnlockSurfaceKHR", "eglSetSwapRectangleANDROID", "eglGetRenderBufferANDROID",
    "eglCreateNativeClientBufferANDROID", "eglGetNativeClientBufferANDROID",
}
FRONT = {"eglGetDisplay", "eglGetPlatformDisplay", "eglGetProcAddress", "eglGetError", "eglQueryString", "eglMakeCurrent",
         "eglBindAPI", "eglChooseConfig", "eglGetConfigAttrib"}

# Android spellings -> Khronos header spellings
TYPES = {"NativeDisplayType": "EGLNativeDisplayType", "NativeWindowType": "EGLNativeWindowType",
         "NativePixmapType": "EGLNativePixmapType"}


def main():
    src, out = sys.argv[1], sys.argv[2]
    text = open(src).read()
    rows = re.findall(r"EGL_ENTRY\(([^;]*?)\)\s*$", text, re.M)
    if len(rows) < 70:
        sys.exit(f"gen-front-entries: only {len(rows)} EGL_ENTRY rows in {src}")
    seen_excl, seen_front, lines, names = set(), set(), [], []
    for row in rows:
        parts = [p.strip() for p in row.split(",")]
        ret, name, params = parts[0], parts[1], parts[2:]
        names.append(name)
        if name in EXCLUDED:
            seen_excl.add(name)
            continue
        if name in FRONT:
            seen_front.add(name)
            continue
        if params == ["void"]:
            typed, args = "void", ""
        else:
            typed = ", ".join(f"{TYPES.get(t, t)} a{i}" for i, t in enumerate(params))
            args = ", ".join(f"a{i}" for i in range(len(params)))
        lines.append(f"    X({TYPES.get(ret, ret)}, {name}, ({typed}), ({args})) \\")
    for want, seen, what in ((EXCLUDED, seen_excl, "excluded"), (FRONT, seen_front, "front")):
        if want - seen:
            sys.exit(f"gen-front-entries: {what} names not in {src}: {sorted(want - seen)}")
    with open(out, "w") as f:
        f.write(f"/* Generated by tools/gen-front-entries.py from {src}; do not edit. */\n")
        f.write(f"/* {len(rows)} loader entries: {len(lines)} forwarded, {len(FRONT)} front, {len(EXCLUDED)} not provided */\n")
        f.write("#define NVN_FRONT_FORWARDED(X) \\\n" + "\n".join(lines) + "\n\n")
        f.write("#define NVN_LOADER_ENTRY_NAMES \\\n" + " \\\n".join(f'    "{n}",' for n in names) + "\n")


if __name__ == "__main__":
    main()
